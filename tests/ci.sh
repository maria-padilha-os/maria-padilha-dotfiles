#!/usr/bin/env bash
# Contract tests for the dotfiles checkout. No live session is needed: the
# linker is exercised against a scratch HOME, and the Hyprland config is only
# parsed, not loaded.
set -uo pipefail

root=$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
dots="$root/bin/padilha-dots"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

pass=0
fail=0
ok() { pass=$((pass + 1)); printf '  ok   %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf '  FAIL %s\n' "$1"; [ -n "${2:-}" ] && printf '       %s\n' "$2"; }

echo "syntax"

while IFS= read -r -d '' file; do
    if lua -e "assert(loadfile('$file'))"; then
        ok "lua parse ${file#"$root"/}"
    else
        bad "lua parse ${file#"$root"/}"
    fi
done < <(find "$root/hypr" -name '*.lua' -print0)

for file in "$dots" "$root/micro/install.sh" "$root/tests/keymaps.sh"; do
    if sh -n "$file"; then
        ok "sh -n ${file#"$root"/}"
    else
        bad "sh -n ${file#"$root"/}"
    fi
done

if command -v shellcheck >/dev/null 2>&1; then
    if shellcheck --severity=warning "$dots" "$root/micro/install.sh" "$root/tests/keymaps.sh"; then
        ok "shellcheck"
    else
        bad "shellcheck"
    fi
fi

echo "json"

while IFS= read -r -d '' file; do
    if python3 -m json.tool <"$file" >/dev/null 2>&1; then
        ok "json ${file#"$root"/}"
    else
        bad "json ${file#"$root"/}"
    fi
done < <(find "$root" -path "$root/.git" -prune -o -name '*.json' -print0)

echo "keymaps"

if "$root/tests/keymaps.sh"; then
    ok "nvim keymap contract"
else
    bad "nvim keymap contract"
fi

echo "firefox"

if python3 "$root/tests/firefox_theme.py"; then
    ok "firefox theme contract"
else
    bad "firefox theme contract"
fi

echo "thunar"

if python3 "$root/tests/thunar_config.py"; then
    ok "thunar and GTK config contract"
else
    bad "thunar and GTK config contract"
fi

echo "discord"

if python3 "$root/tests/discord_theme.py"; then
    ok "discord theme contract"
else
    bad "discord theme contract"
fi

echo "app themes"

if python3 "$root/tests/app_theme_config.py"; then
    ok "app theme fallback contract"
else
    bad "app theme fallback contract"
fi

echo "linking"

home="$tmp/home"
mkdir -p "$home/.config"
if HOME="$home" XDG_CONFIG_HOME="$home/.config" "$dots" hypr nvim wezterm mc >/dev/null 2>&1; then
    ok "padilha-dots links a scratch config"
else
    bad "padilha-dots links a scratch config"
fi

for name in hypr nvim wezterm; do
    if [ -L "$home/.config/$name" ]; then
        ok "$name is a symlink"
    else
        bad "$name is a symlink"
    fi
done

mc_ini="$home/.config/mc/ini"
if [ -f "$mc_ini" ] && [ ! -L "$mc_ini" ]; then
    ok "mc ini is copied"
else
    bad "mc ini is copied"
fi
if [ -L "$home/.config/mc/mc.keymap" ]; then
    ok "mc keymap is linked"
else
    bad "mc keymap is linked"
fi

printf '\n[local-test]\nvalue=keep\n' >>"$mc_ini"
HOME="$home" XDG_CONFIG_HOME="$home/.config" "$dots" mc >/dev/null 2>&1
if grep -q '^value=keep$' "$mc_ini"; then
    ok "a local mc change is kept"
else
    bad "a local mc change is kept"
fi

if HOME="$tmp/no-profile" XDG_CONFIG_HOME="$tmp/no-profile/.config" "$dots" firefox >/dev/null 2>&1; then
    ok "firefox without a profile is not an error"
else
    bad "firefox without a profile is not an error"
fi

ff_home="$tmp/firefox-home"
ff_profile="$ff_home/.mozilla/firefox/abc.default-release"
mkdir -p "$ff_profile/chrome"
printf '%s\n' \
    '[Profile0]' 'Name=default-release' 'IsRelative=1' \
    "Path=abc.default-release" 'Default=1' >"$ff_home/.mozilla/firefox/profiles.ini"
if HOME="$ff_home" XDG_CONFIG_HOME="$ff_home/.config" "$dots" firefox >/dev/null 2>&1; then
    ok "padilha-dots installs into a scratch Firefox profile"
else
    bad "padilha-dots installs into a scratch Firefox profile"
fi
for name in userChrome.css userContent.css; do
    if [ -L "$ff_profile/chrome/$name" ]; then
        ok "firefox $name is linked"
    else
        bad "firefox $name is linked"
    fi
done
if [ -f "$ff_profile/user.js" ] && [ ! -L "$ff_profile/user.js" ]; then
    ok "firefox user.js is copied"
else
    bad "firefox user.js is copied"
fi
# The palette is generated by padilha-theme at runtime; a stub is enough to
# check that the installed sheets keep their relative import in the profile.
printf '%s\n' '/* generated palette stub */' >"$ff_profile/chrome/lilith.css"
if [ -f "$ff_profile/chrome/lilith.css" ]; then
    ok "firefox generated palette lives beside the linked sheets"
else
    bad "firefox generated palette lives beside the linked sheets"
fi

if HOME="$tmp/micro" XDG_CONFIG_HOME="$tmp/micro/.config" "$root/micro/install.sh" --no-plugins >/dev/null 2>&1; then
    ok "micro installer runs without plugins"
else
    bad "micro installer runs without plugins"
fi
if [ -L "$tmp/micro/.config/micro/settings.json" ]; then
    ok "micro settings are linked"
else
    bad "micro settings are linked"
fi
micro_colour="$tmp/micro/.config/micro/colorschemes/padilha.micro"
if [ -f "$micro_colour" ] && [ ! -L "$micro_colour" ]; then
    ok "micro colourscheme fallback is seeded as a file"
else
    bad "micro colourscheme fallback is seeded as a file"
fi
printf '\n# local-generated-colour\n' >>"$micro_colour"
if HOME="$tmp/micro" XDG_CONFIG_HOME="$tmp/micro/.config" "$root/micro/install.sh" --no-plugins >/dev/null 2>&1; then
    ok "micro installer runs again"
else
    bad "micro installer runs again"
fi
if grep -q '^# local-generated-colour$' "$micro_colour"; then
    ok "micro installer keeps an existing generated colourscheme"
else
    bad "micro installer keeps an existing generated colourscheme"
fi

# Thunar keeps generated colour CSS next to settings.ini. Seed a sentinel and
# make sure the linker only adds settings.ini.
th_home="$tmp/thunar-home"
mkdir -p "$th_home/.config/gtk-3.0"
printf '%s\n' '/* generated sentinel */' >"$th_home/.config/gtk-3.0/gtk.css"
printf '%s\n' '/* generated thunar sentinel */' >"$th_home/.config/gtk-3.0/thunar.css"
if HOME="$th_home" XDG_CONFIG_HOME="$th_home/.config" "$dots" thunar >/dev/null 2>&1; then
    ok "padilha-dots links Thunar and GTK in a scratch config"
else
    bad "padilha-dots links Thunar and GTK in a scratch config"
fi
for rel in Thunar/thunarrc Thunar/uca.xml gtk-3.0/settings.ini gtk-4.0/settings.ini; do
    if [ -L "$th_home/.config/$rel" ]; then
        ok "$rel is linked"
    else
        bad "$rel is linked"
    fi
done
for rel in thunarrc uca.xml; do
    if [ "$(readlink -f "$th_home/.config/Thunar/$rel")" = "$root/thunar/$rel" ]; then
        ok "Thunar $rel resolves to the checkout"
    else
        bad "Thunar $rel resolves to the checkout"
    fi
done
if [ "$(cat "$th_home/.config/gtk-3.0/gtk.css")" = '/* generated sentinel */' ] && [ ! -L "$th_home/.config/gtk-3.0/gtk.css" ]; then
    ok "the generated gtk.css is not overwritten"
else
    bad "the generated gtk.css is not overwritten"
fi
if [ "$(cat "$th_home/.config/gtk-3.0/thunar.css")" = '/* generated thunar sentinel */' ] && [ ! -L "$th_home/.config/gtk-3.0/thunar.css" ]; then
    ok "the generated thunar.css is not overwritten"
else
    bad "the generated thunar.css is not overwritten"
fi
HOME="$th_home" XDG_CONFIG_HOME="$th_home/.config" "$dots" thunar >/dev/null 2>&1
if [ "$(cat "$th_home/.config/gtk-3.0/gtk.css")" = '/* generated sentinel */' ]; then
    ok "rerunning the linker keeps the generated gtk.css"
else
    bad "rerunning the linker keeps the generated gtk.css"
fi

gtk_home="$tmp/gtk-home"
if HOME="$gtk_home" XDG_CONFIG_HOME="$gtk_home/.config" "$dots" gtk >/dev/null 2>&1; then
    ok "padilha-dots gtk links only the GTK settings"
else
    bad "padilha-dots gtk links only the GTK settings"
fi
if [ -L "$gtk_home/.config/gtk-3.0/settings.ini" ] && [ ! -e "$gtk_home/.config/Thunar" ]; then
    ok "the gtk target does not install Thunar"
else
    bad "the gtk target does not install Thunar"
fi
if [ -L "$gtk_home/.config/gtk-4.0/settings.ini" ]; then
    ok "the gtk target links the GTK 4 settings"
else
    bad "the gtk target links the GTK 4 settings"
fi

# cava, fuzzel, btop's theme and Spicetify's palette are generated whole by
# padilha-theme. They must be seeded as real files only when absent, so a later
# apply never writes into this checkout.
app_home="$tmp/app-home"
mkdir -p "$app_home/.config/gtk-3.0" "$app_home/.config/gtk-4.0"
printf '%s\n' '/* generated gtk3 sentinel */' >"$app_home/.config/gtk-3.0/gtk.css"
printf '%s\n' '/* generated gtk4 sentinel */' >"$app_home/.config/gtk-4.0/gtk.css"
if HOME="$app_home" XDG_CONFIG_HOME="$app_home/.config" "$dots" cava fuzzel spicetify btop gtk >/dev/null 2>&1; then
    ok "padilha-dots seeds the app fallbacks"
else
    bad "padilha-dots seeds the app fallbacks"
fi
for rel in cava/config fuzzel/fuzzel.ini spicetify/config-xpui.ini spicetify/Themes/caelestia/color.ini btop/themes/caelestia.theme; do
    if [ -f "$app_home/.config/$rel" ] && [ ! -L "$app_home/.config/$rel" ]; then
        ok "$rel is seeded as a file"
    else
        bad "$rel is seeded as a file"
    fi
done
if [ -L "$app_home/.config/btop/btop.conf" ]; then
    ok "btop.conf remains linked"
else
    bad "btop.conf remains linked"
fi
for rel in gtk-3.0/settings.ini gtk-4.0/settings.ini; do
    if [ -L "$app_home/.config/$rel" ]; then
        ok "$rel is linked by the app fallback run"
    else
        bad "$rel is linked by the app fallback run"
    fi
done
if [ "$(cat "$app_home/.config/gtk-3.0/gtk.css")" = '/* generated gtk3 sentinel */' ] &&
    [ "$(cat "$app_home/.config/gtk-4.0/gtk.css")" = '/* generated gtk4 sentinel */' ]; then
    ok "the app fallback run keeps both generated gtk.css files"
else
    bad "the app fallback run keeps both generated gtk.css files"
fi
printf '\n# local-generated-cava\n' >>"$app_home/.config/cava/config"
printf '\n# local-generated-btop\n' >>"$app_home/.config/btop/themes/caelestia.theme"
HOME="$app_home" XDG_CONFIG_HOME="$app_home/.config" "$dots" cava btop >/dev/null 2>&1
if grep -q '^# local-generated-cava$' "$app_home/.config/cava/config"; then
    ok "a generated cava config is not overwritten by the fallback"
else
    bad "a generated cava config is not overwritten by the fallback"
fi
if grep -q '^# local-generated-btop$' "$app_home/.config/btop/themes/caelestia.theme"; then
    ok "a generated btop theme is not overwritten by the fallback"
else
    bad "a generated btop theme is not overwritten by the fallback"
fi

printf '\n%d passed, %d failed\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
